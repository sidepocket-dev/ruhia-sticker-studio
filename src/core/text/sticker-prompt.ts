import { COMPOSITION_LABELS } from './poses.js';
import type { StickerPlan } from './plan.js';
import { findStyle } from './styles.js';
import type { StylePresetId } from './styles.js';

/**
 * 画像生成プロンプトを組み立てる。
 *
 * 必ず入れる条件は、どれも実測に裏づけがある。
 *
 * ・「幅広で完全に透明な隙間」「背景・影なし」
 *     隙間の広いシートは単純分割で取り出せ、そうでないシートは
 *     高度な解析が必要になる（PRODUCT_SPEC.md §10 / §77.4）。
 *
 * ・「キャラクターを1体だけ」
 *     相手が必要な動作を指示したとき、2体描かれたことがある（§77.15）。
 *
 * ・「白い縁を付ける」
 *     見た目が良くなるうえ、白い縁が本体・文字・装飾をつないで
 *     1つの連結領域にするため、抽出が安定する（§77.21）。
 *     縁を後から描き足そうとしてはいけない。背景が不透明な画像では、
 *     白い縁と白い背景は同じ色でつながっており、色だけでは区別できない。
 *
 * この文面が必ず成功すると表現してはならない。あくまで推奨（§34）。
 */

/** 1行のスタンプ指定。 */
function stickerLine(plan: StickerPlan, index: number): string {
  return `${index + 1}. 「${plan.text}」／${plan.action}／${COMPOSITION_LABELS[plan.pose.composition]}`;
}

/** キャラクターの扱い。参照画像を正とし、特定のキャラクターの特徴は書かない。 */
function characterRules(sheetCount: number): string[] {
  const lines = [
    '添付画像のキャラクターをそのまま使用してください。',
    '参照画像で確認できる外見、衣装、体の特徴を維持してください。',
    '各ステッカーにはキャラクターを1体だけ描いてください。',
  ];
  if (sheetCount > 1) {
    lines.splice(2, 0, `${sheetCount}枚すべてで同一キャラクターとして統一してください。`);
  }
  return lines;
}

/** 見た目の共通条件。 */
function designRules(styleId: StylePresetId, sheetCount: number): string[] {
  const lines = [
    'セリフは日本語として正確で、はっきり読みやすく描いてください。',
    'ステッカーらしく、各ステッカー全体の外周には白い縁を設けてください。',
    '文字のレイアウトや感情を補助する表現は、各セリフとポーズに自然に合うものを使ってください。',
  ];
  if (sheetCount > 1) {
    lines.push(
      `${sheetCount}枚すべてを同じシリーズとして、キャラクターの描き方、質感、文字表現、仕上がりに統一感を持たせてください。`,
      `${sheetCount}枚の間で別の画風や別シリーズのデザインにならないようにしてください。`,
    );
  }
  return [...lines, ...findStyle(styleId).lines];
}

/** 並べ方の共通条件。抽出の成否に直結する。 */
const LAYOUT_RULES = [
  'ステッカー同士の間には、幅広い完全透明の隙間を設けてください。',
  '各ステッカーは完全に独立させ、隣のステッカーと接触・重複させないでください。',
  '背景、床、背景装飾、背景色、影は追加しないでください。',
];

/** シート1枚ぶんのプロンプト。 */
export function buildStickerPrompt(
  plans: StickerPlan[],
  styleId: StylePresetId = 'auto',
): string {
  return [
    '添付したキャラクターで、ステッカーシートを1枚作ってください。',
    '',
    '3×3のグリッドに9種類の異なるステッカーを配置した、',
    '正方形（1:1）の完全透明背景のステッカーシートを1枚作成してください。',
    '',
    '各ステッカーには以下のセリフをそれぞれ1つだけ使い、',
    '指定した表情・ポーズ・見せ方で描いてください。',
    '',
    ...plans.map(stickerLine),
    '',
    '【キャラクター】',
    ...characterRules(1),
    '',
    '【デザイン】',
    ...designRules(styleId, 1),
    '',
    '【レイアウト】',
    ...LAYOUT_RULES,
  ].join('\n');
}

/**
 * 複数シートを1回の依頼でまとめて作るプロンプト（追加仕様 §1.2 / §2）。
 *
 * まとめて頼むと、1枚ずつ頼むよりシリーズ感が揃いやすい傾向が確認されている
 * （追加仕様 §8）。ただしモデルによっては複数枚を返せないため、
 * 1枚ずつのモードは必ず残す。
 *
 * **文面は実機で5枚生成できたテンプレートをそのまま使う。**
 * 以前の文面では、依頼した枚数を返さない失敗が2通り起きた。
 *
 *   1. 同じシートが重複して2枚しか返らない
 *   2. 同じ内容を2枚作り「どちらがいいですか」と聞いて止まる
 *
 * 「何枚ほしいか」だけでは足りず、**生成の手順そのもの**を書くと安定した。
 *
 *   ・1回の生成で全シートを表すのではない、と否定形で言う
 *   ・「画像1 = シート1のみ」と、出力単位を明示する
 *   ・別バージョンの生成、途中の確認、1枚での終了を名指しで禁止する
 *   ・確認を挟まず次のシートへ進む、と手順で書く
 *
 * ただし、これで必ず5枚返るとは書けない。画像生成を何回呼ぶかは
 * 文面だけでは決められないため、1枚ずつのモードを残す（§34）。
 *
 * 検証済みの文面に、書かれていない指示を足さないこと。
 * 仕上がり設定だけは例外で、デザインの節へ加わる。
 */
export function buildBatchStickerPrompt(
  sheets: StickerPlan[][],
  styleId: StylePresetId = 'auto',
): string {
  const count = sheets.length;
  const total = count * 9;
  /** 画像1 = シート1のみ … の対応表 */
  const mapping = Array.from(
    { length: count },
    (_, index) => `- 画像${index + 1} = シート${index + 1}のみ`,
  );
  /** シート2、シート3、… 確認を挟まず進む先 */
  const rest = Array.from({ length: count - 1 }, (_, index) => `シート${index + 2}`).join('、');

  const sheetBlocks = sheets.flatMap((plans, index) => [
    `# シート${index + 1}`,
    ...plans.map(stickerLine),
    '',
  ]);

  return [
    `添付したキャラクターを使って、独立したステッカーシートを${count}枚生成してください。`,
    '',
    '【最重要：出力手順】',
    `この依頼では、画像を合計${count}枚生成してください。`,
    '',
    `1回の画像生成で${count}シートを表現するのではありません。`,
    `「シート1」から「シート${count}」までを、1シートにつき1枚の独立した画像として順番に生成してください。`,
    '',
    '出力単位は必ず以下です。',
    ...mapping,
    '',
    '各画像には、そのシートで指定された9種類だけを含めてください。',
    '',
    '【禁止事項】',
    `- ${total}種類を1枚の画像にまとめない`,
    `- ${count}シートを1枚のコラージュにしない`,
    '- 複数シートを同じ画像内に配置しない',
    '- 同じシートの別バージョンを複数生成しない',
    '- 1枚だけ生成して終了しない',
    '- 途中でユーザーに選択を求めない',
    '- 「どちらがいいですか」などの確認を行わない',
    '- シート1生成後に停止しない',
    '',
    `シート1の生成が完了したら、ユーザーへの確認を挟まず、そのまま${rest}まで順番に生成してください。`,
    '',
    '最終的な成果物は、',
    `3×3ステッカーシート × ${count}枚 = ${total}種類`,
    'です。',
    '',
    '各画像はそれぞれ、',
    '- 3×3グリッド',
    '- 9種類のステッカー',
    '- 正方形（1:1）',
    '- 完全透明背景',
    '',
    'の独立したステッカーシートにしてください。',
    '',
    '【キャラクター】',
    ...characterRules(count),
    '',
    '【デザイン】',
    ...designRules(styleId, count),
    '',
    '【レイアウト】',
    ...LAYOUT_RULES,
    `${count}枚とも完全透明背景の正方形ステッカーシートとして別々に出力してください。`,
    '',
    ...sheetBlocks,
    `シート1からシート${count}までを、それぞれ独立した画像として合計${count}枚生成してください。`,
    `${total}種類を1枚の画像にまとめないでください。`,
    `1枚生成した時点で終了せず、必ず${count}枚すべて生成してください。`,
  ].join('\n');
}

/**
 * 途中で止まったときに、同じ会話へ続けて送る文（§77.22）。
 *
 * まとめて頼んでも、モデルが画像生成を1回しか呼ばずに終わることがある。
 * 文面をどれだけ強くしても、何回生成するかは文面では決められないため、
 * この場合は**同じ会話のまま続きを頼む**のがいちばん確実。
 *
 * 新しい会話を始めてはいけない。直前のシートを見ながら描けるので、
 * 別々に頼むよりシリーズ感が保たれる。できたシートの作り直しも要らない。
 *
 * **一行だけの依頼にしてはいけない。** 実測では、
 * 「残りのシート2〜5を続けて生成して」とだけ頼んだところ、
 * 画風は引き継げたが**4シートぶんを縮小して1枚に詰め込まれた。**
 * 会話の続きでも出力単位は引き継がれないため、
 * まとめて頼むときと同じ手順・出力単位・禁止事項をもう一度書く。
 */
export function buildContinuePrompt(count: number, done = 1): string {
  /** これから作る枚数 */
  const rest = count - done;
  const total = rest * 9;
  const range = rest === 1 ? `シート${count}` : `シート${done + 1}〜${count}`;
  const made = done === 1 ? 'シート1' : `シート1〜${done}`;
  const mapping = Array.from(
    { length: rest },
    (_, index) => `- 画像${index + 1} = シート${done + index + 1}のみ`,
  );

  /** 残り1枚のときは、複数枚を分ける説明が噛み合わない */
  const order =
    rest === 1
      ? [`「シート${count}」を、独立した画像1枚として生成してください。`]
      : [
          `1回の画像生成で${rest}シートを表現するのではありません。`,
          `「シート${done + 1}」から「シート${count}」までを、1シートにつき1枚の独立した画像として順番に生成してください。`,
        ];

  const banned = [
    ...(rest === 1
      ? []
      : [`- ${total}種類を1枚の画像にまとめない`, `- ${rest}シートを1枚のコラージュにしない`]),
    '- 複数シートを同じ画像内に配置しない',
    '- ステッカーを小さくして1枚に詰め込まない',
    `- ${made}を作り直さない`,
    ...(rest === 1 ? [] : ['- 1枚だけ生成して終了しない']),
    '- 途中でユーザーに選択を求めない',
  ];

  return [
    `残りの${range}を、今の${made}と同じ雰囲気・デザインで続けて生成してください。`,
    '',
    '【最重要：出力手順】',
    `ここでは、画像を合計${rest}枚生成してください。`,
    '',
    ...order,
    '',
    '出力単位は必ず以下です。',
    ...mapping,
    '',
    '各画像には、そのシートで指定された9種類だけを含めてください。',
    '各画像はそれぞれ、3×3グリッド、9種類のステッカー、正方形（1:1）、完全透明背景の独立したステッカーシートにしてください。',
    '',
    '【禁止事項】',
    ...banned,
    '',
    `${made}の続きとして、キャラクター、画風、文字表現、仕上がりをそろえてください。`,
  ].join('\n');
}

/** すべてのシートぶんのプロンプトを、シート番号つきで返す。 */
export function buildAllStickerPrompts(
  sheets: StickerPlan[][],
  styleId: StylePresetId = 'auto',
): { sheet: number; prompt: string }[] {
  return sheets.map((plans, index) => ({
    sheet: index + 1,
    prompt: buildStickerPrompt(plans, styleId),
  }));
}
